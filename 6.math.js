// Math - built in object that provides a collection of properties and methods

console.log(Math.PI); //PI
console.log(Math.E); //Euler's Number

console.log(Math.round(3.50));

console.log(Math.floor(3.89));

console.log(Math.ceil(3.23));

console.log(Math.trunc(5.4546)); //removes decimals

console.log(Math.pow(3,2));

console.log(Math.sqrt(144));

console.log(Math.log10(10)); //log with base 10

console.log(Math.sin(90)); //angles in radians

console.log(Math.cos(90));

console.log(Math.abs(-23)); //returns always a positive value

console.log(Math.sign(-232)); //returns 1 if number is positive, -1 if negative and 0 for zero

console.log(Math.max(23,43,15,6,63,1,23));

console.log(Math.min(23,43,15,6,63,1,23));
